# ------------------------------------------------------------------ 工具
_PUNCT = re.compile(r"[\s，。！？、,.!?~～…—\-\[\]【】()（）\"'“”‘’:：;；]+")


def norm(text: str) -> str:
    return _PUNCT.sub("", (text or "").strip().lower())


def _fill(line: str, state: PetState, owner: str) -> str:
    return line.replace("{owner}", owner).replace("{name}", state.name)


def _pick(options: list) -> str:
    return random.choice(options)


# ------------------------------------------------------------------ 状态前缀
def _prefix(state: PetState) -> str:
    s = state.stats
    if state.sleeping and random.random() < 0.7:
        return "（迷迷糊糊地睁开眼）"
    if s["hunger"] < 22 and random.random() < 0.6:
        return _pick(["（肚子咕噜噜叫）", "（有气无力地）", "（摸了摸扁扁的肚子）"])
    if s["energy"] < 20 and random.random() < 0.5:
        return "（打了个大大的哈欠）"
    if s["clean"] < 22 and random.random() < 0.5:
        return "（身上的毛有点乱）"
    if s["mood"] < 25 and random.random() < 0.5:
        return "（耳朵垂下来）"
    return ""


