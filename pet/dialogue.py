# ------------------------------------------------------------------ 主入口
def reply(text: str, state: PetState, owner: str = "主人") -> tuple[str, str]:
    """根据用户输入和宠物状态，返回 (回复, 情绪)。"""
    q = norm(text)
    if not q:
        return _fill(_pick(["嗯？你想说什么呀？", "我在听哦，你慢慢说。"]), state, owner), "normal"

    for keys, answers, emo in INTENTS:
        if any(k in q for k in keys):
            line = _fill(_pick(answers), state, owner)
            if random.random() < 0.45:
                line = _prefix(state) + line
            if state.stats["hunger"] < 22 and random.random() < 0.3:
                line += "（对了……我有点饿了）"
            return line, emo

    # 纯数字 / 很短的话
    if len(q) <= 2:
        line = _fill(_pick([
            "嗯嗯？", "喵？", "然后呢？", "（歪头）你在说什么呀。",
        ]), state, owner)
        return line, "normal"

    s = state.stats
    if s["hunger"] < 25 and random.random() < 0.6:
        return _pick(FALLBACK_HUNGRY), "sad"
    if s["energy"] < 22 and random.random() < 0.5:
        return _pick(FALLBACK_SLEEPY), "sleepy"
    if s["mood"] > 78 and random.random() < 0.5:
        return _pick(FALLBACK_HAPPY), "happy"
    return _pick(FALLBACK_GENERAL), "normal"


