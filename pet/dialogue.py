        f"用户希望你称呼他为「{owner}」。\n"
        f"你的当前状态：等级 {state.level}（{stage}），饱食度 {s['hunger']:.0f}，"
        f"精力 {s['energy']:.0f}，清洁度 {s['clean']:.0f}，心情 {s['mood']:.0f}，"
        f"{'正在睡觉' if state.sleeping else '醒着'}。\n"
