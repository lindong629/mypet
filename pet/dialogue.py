def idle_line(state: PetState, owner: str) -> tuple[str, str]:
    """宠物主动开口，返回 (文本, 情绪)。"""
    s = state.stats
    if state.sleeping:
        return "", "sleepy"
    if s["hunger"] < 30 and random.random() < 0.55:
        return _pick(IDLE_NEED["hungry"]), "sad"
    if s["energy"] < 28 and random.random() < 0.5:
        return _pick(IDLE_NEED["tired"]), "sleepy"
    if s["clean"] < 30 and random.random() < 0.45:
        return _pick(IDLE_NEED["dirty"]), "sad"
    if s["mood"] < 30 and random.random() < 0.5:
        return _pick(IDLE_NEED["sad"]), "sad"
    if s["mood"] > 75 and random.random() < 0.4:
        return _pick(FALLBACK_HAPPY), "happy"
    return _fill(_pick(IDLE_CASUAL), state, owner), "normal"


